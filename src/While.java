public class While{
    public static void main(String[] args) {

        // sisteminha simples de contador só pra demonstrar o while
        int Vidas = 5;

        while (Vidas > 0) {
            System.out.println("Você tem " + Vidas + " Vidas");
            Vidas--;
        }
        System.out.println("Game over");

        }
    }

